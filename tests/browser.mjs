import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {mkdir} from 'node:fs/promises';
const origin=process.env.POCKETWORLD_URL||'https://pocketworld-github-web-production.up.railway.app';
const screenshotDir='artifacts/browser';
await mkdir(screenshotDir,{recursive:true});
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const errors=[];
try{
 const context=await browser.newContext({viewport:{width:1440,height:900},deviceScaleFactor:1});
 const page=await context.newPage();
 page.on('pageerror',e=>errors.push(e.message));
 page.on('dialog',async d=>{
   if(d.type()==='prompt')await d.accept('35');
   else if(d.type()==='confirm')await d.accept();
   else await d.dismiss();
 });
 await page.goto(origin,{waitUntil:'domcontentloaded',timeout:30000});
 await page.locator('#join-form input[name="name"]').waitFor({timeout:30000});
 await page.screenshot({path:screenshotDir+'/landing-desktop.png',fullPage:true});
 await page.locator('#join-form input[name="name"]').fill('E2E-browser-'+randomUUID().slice(0,7));
 await page.locator('#join-form button').click();
 await page.locator('.sidebar').waitFor({timeout:15000});
 assert.match(await page.locator('h2').first().innerText(),/Your universe/i);
 await page.screenshot({path:screenshotDir+'/dashboard-desktop.png',fullPage:true});
 await page.locator('.sidebar [data-nav="shop"]').click();
 await page.locator('button[data-action="buy"][data-value="moon-fox"]').click();
 await page.locator('.wallet').waitFor();
 assert.match(await page.locator('.wallet').innerText(),/90/);
 await page.locator('.sidebar [data-nav="world"]').click();
 await page.locator('button[data-action="equip"]').first().click();
 await page.locator('.world-companion svg').waitFor();
 await page.screenshot({path:screenshotDir+'/my-world-desktop.png',fullPage:true});
 await page.locator('.sidebar [data-nav="collection"]').click();
 await page.locator('button[data-action="list"]').first().click();
 await page.locator('.sidebar [data-nav="market"]').click();
 assert.ok(await page.locator('button[data-action="marketcancel"]').count()>=1);
 await page.screenshot({path:screenshotDir+'/community-market-desktop.png',fullPage:true});
 await page.locator('button[data-action="marketcancel"]').first().click();
 await page.locator('.sidebar [data-nav="gifts"]').click();
 await page.locator('#card-form [name="recipient"]').fill('A special friend');
 await page.locator('#card-form [name="message"]').fill('Keep making tiny wonders!');
 await page.locator('#card-form button[type="submit"]').click();
 await page.locator('.gift-row').first().waitFor();
 await page.screenshot({path:screenshotDir+'/gifting-desktop.png',fullPage:true});
 const mobile=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const phone=await mobile.newPage();
 phone.on('pageerror',e=>errors.push(e.message));
 await phone.goto(origin,{waitUntil:'domcontentloaded',timeout:30000});
 await phone.locator('#join-form input').waitFor({timeout:20000});
 await phone.screenshot({path:screenshotDir+'/landing-mobile.png',fullPage:true});
 await phone.locator('#join-form input').fill('E2E-mobile-'+randomUUID().slice(0,8));
 await phone.locator('#join-form button').click();
 await phone.locator('.mobilebar').waitFor();
 await phone.locator('.mobilebar [data-nav="world"]').click();
 await phone.locator('.world-stage').waitFor();
 await phone.screenshot({path:screenshotDir+'/my-world-mobile.png',fullPage:true});
 const width=await phone.evaluate(()=>({scroll:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
 assert.ok(width.scroll<=width.client+3,'Mobile horizontal overflow '+JSON.stringify(width));
 assert.deepEqual(errors,[],'No browser JS exceptions');
 await mobile.close();await context.close();
 console.log('PASS desktop + mobile actual browser flow, purchase with play coins, world, market, personal gifting; screenshots captured');
}catch(err){console.error('Browser e2e failed:',err);throw err;}finally{await browser.close();}
