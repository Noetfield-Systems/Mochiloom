(async function runSmoke() {
  const assert = await import("node:assert/strict");
  const fs = await import("node:fs");
  const vm = await import("node:vm");
  const {randomUUID} = await import("node:crypto");
  const ROOT = process.env.POCKETWORLD_URL || "https://pocketworld-web-production.up.railway.app";
  const source = fs.readFileSync(new URL("../src/index.ts", import.meta.url), "utf8");
  const script = source.match(/<script>([\s\S]+?)<\/script>/);
  assert.ok(script, "browser script exists");
  new vm.Script(script[1]);
  console.log("PASS client JS parses");
  async function api(path,body,cookie) {
    const res=await fetch(ROOT+path,{method:body===undefined?"GET":"POST",headers:{"content-type":"application/json",...(cookie?{cookie}:{})},body:body===undefined?undefined:JSON.stringify(body)});
    const json=await res.json().catch(()=>({}));
    return {status:res.status,json,cookie:res.headers.get("set-cookie")?.split(";")[0]||null};
  }
  function requireSuccess(result,label) {
    assert.equal(result.status,200,label+" status "+result.status+": "+JSON.stringify(result.json));
    assert.equal(result.json.ok,true,label+" body");
    console.log("PASS "+label);
    return result;
  }
  const health=requireSuccess(await api("/health"),"health");
  assert.equal(health.json.storage,"postgres");
  const html=await fetch(ROOT+"/");
  assert.equal(html.status,200);
  const renderedHtml=await html.text();
  assert.match(renderedHtml,/PocketWorld|pocketworld/i);
  const renderedScript=renderedHtml.match(/<script>([\s\S]+?)<\/script>/);
  assert.ok(renderedScript,"deployed HTML has a browser script");
  new vm.Script(renderedScript[1]);
  console.log("PASS deployed HTML browser script parses after server rendering");
  console.log("PASS public frontend");
  const unauth=requireSuccess(await api("/api/bootstrap"),"anonymous bootstrap");
  assert.equal(unauth.json.user,null);
  assert.ok(unauth.json.catalogue.length>=8);
  const name="E2E-"+randomUUID().slice(0,8);
  const created=requireSuccess(await api("/api/guest",{name}),"guest registration");
  assert.ok(created.cookie?.startsWith("pw_session="));
  const cookie=created.cookie;
  const profile=requireSuccess(await api("/api/bootstrap",undefined,cookie),"authenticated profile");
  assert.equal(profile.json.user.display_name,name);
  assert.equal(profile.json.user.coins,180);
  const buy=requireSuccess(await api("/api/buy",{item:"sunbeam-sticker"},cookie),"virtual collectible purchase");
  assert.equal(buy.json.coins,145);
  const updated=requireSuccess(await api("/api/bootstrap",undefined,cookie),"inventory persisted");
  assert.ok(updated.json.inventory.some(x=>x.id===buy.json.item_id));
  const badItem=await api("/api/buy",{item:"not-an-item"},cookie);
  assert.equal(badItem.status,400);
  console.log("PASS unknown product refused");
  const browserOrigin=await fetch(ROOT+"/api/challenge",{method:"POST",headers:{"Content-Type":"application/json","Origin":ROOT,"Cookie":cookie},body:"{}"});
  assert.equal(browserOrigin.status,200,"valid browser Origin must be accepted behind Railway reverse proxy");
  const hostileOrigin=await fetch(ROOT+"/api/challenge",{method:"POST",headers:{"Content-Type":"application/json","Origin":"https://other.example","Cookie":cookie},body:"{}"});
  assert.equal(hostileOrigin.status,403,"foreign browser Origin must be rejected");
  console.log("PASS browser Origin acceptance and cross-site rejection");
  const challenge=requireSuccess(await api("/api/challenge",{},cookie),"memory challenge");
  assert.match(challenge.json.sequence,/^[0-3]{5}$/);
  const played=requireSuccess(await api("/api/play",{id:challenge.json.id,answer:challenge.json.sequence},cookie),"correct game round");
  assert.equal(played.json.coins,20);
  const replay=await api("/api/play",{id:challenge.json.id,answer:challenge.json.sequence},cookie);
  assert.equal(replay.status,409);
  console.log("PASS replay/duplicate reward refused");
  const playedProfile=requireSuccess(await api("/api/bootstrap",undefined,cookie),"updated virtual balance");
  assert.equal(playedProfile.json.user.coins,165);
  assert.equal(playedProfile.json.user.xp,25);
  const c=requireSuccess(await api("/api/card/create",{recipient:"A friend",message:"We made something wonderful.",theme:"birthday"},cookie),"greeting card creation");
  const publicCard=requireSuccess(await api("/api/card?id="+c.json.id),"public shared card");
  assert.equal(publicCard.json.card.recipient,"A friend");
  const tomorrow=new Date(Date.now()+86400000*2).toISOString();
  requireSuccess(await api("/api/capsule/create",{title:"Future note",message:"Hello, future me!",date:tomorrow},cookie),"sealed time capsule");
  const caps=requireSuccess(await api("/api/bootstrap",undefined,cookie),"capsule privacy");
  assert.ok(caps.json.capsules.some(x=>x.title==="Future note"&&x.message===null));
  const gift=requireSuccess(await api("/api/gift",{inventoryId:buy.json.item_id},cookie),"gift creation");
  assert.match(gift.json.code,/^[A-F0-9]{20}$/);
  const selfClaim=await api("/api/redeem",{code:gift.json.code},cookie);
  assert.equal(selfClaim.status,409);
  console.log("PASS sender cannot redeem own gift");
  const second=requireSuccess(await api("/api/guest",{name:"E2E-"+randomUUID().slice(0,8)}),"recipient registration");
  assert.ok(second.cookie);
  const redeemed=requireSuccess(await api("/api/redeem",{code:gift.json.code},second.cookie),"gift redemption");
  assert.equal(redeemed.json.item,"sunbeam-sticker");
  const doubleClaim=await api("/api/redeem",{code:gift.json.code},second.cookie);
  assert.equal(doubleClaim.status,409);
  console.log("PASS double gift claim refused");
  const recipient=requireSuccess(await api("/api/bootstrap",undefined,second.cookie),"recipient inventory");
  assert.ok(recipient.json.inventory.some(x=>x.item_id==="sunbeam-sticker"));
  const listedItem=requireSuccess(await api("/api/buy",{item:"starry-sticker"},cookie),"purchase item for community resale");
  const listed=requireSuccess(await api("/api/market/list",{inventoryId:listedItem.json.item_id,price:50},cookie),"create marketplace listing");
  const sellerSelfBuy=await api("/api/market/buy",{id:listed.json.id},cookie);
  assert.equal(sellerSelfBuy.status,409);
  console.log("PASS seller cannot buy own listing");
  const browse=requireSuccess(await api("/api/bootstrap",undefined,second.cookie),"buyer marketplace listings");
  assert.ok(browse.json.market.some(x=>x.id===listed.json.id));
  const marketBought=requireSuccess(await api("/api/market/buy",{id:listed.json.id},second.cookie),"atomic secondary market purchase");
  assert.equal(marketBought.json.fee,3);
  assert.equal(marketBought.json.proceeds,47);
  const marketDouble=await api("/api/market/buy",{id:listed.json.id},second.cookie);
  assert.equal(marketDouble.status,409);
  console.log("PASS secondary market double-spend refused");
  const sellerAfter=requireSuccess(await api("/api/bootstrap",undefined,cookie),"seller coins credited");
  assert.equal(sellerAfter.json.user.coins,167);
  const buyerAfter=requireSuccess(await api("/api/bootstrap",undefined,second.cookie),"buyer ownership updated");
  assert.equal(buyerAfter.json.user.coins,130);
  assert.ok(buyerAfter.json.inventory.some(x=>x.item_id==="starry-sticker"));
  const toCancel=requireSuccess(await api("/api/buy",{item:"sunbeam-sticker"},cookie),"buy item to test listing cancellation");
  const cancellable=requireSuccess(await api("/api/market/list",{inventoryId:toCancel.json.item_id,price:60},cookie),"create cancellable listing");
  requireSuccess(await api("/api/market/cancel",{id:cancellable.json.id},cookie),"cancel and return listing escrow");
  const cancelledBuy=await api("/api/market/buy",{id:cancellable.json.id},second.cookie);
  assert.equal(cancelledBuy.status,409);
  const afterCancel=requireSuccess(await api("/api/bootstrap",undefined,cookie),"cancelled collectible returned");
  assert.ok(afterCancel.json.inventory.some(x=>x.item_id==="sunbeam-sticker"));
  console.log("PASS marketplace cancellation and escrow return");
  const roomPurchase=requireSuccess(await api("/api/buy",{item:"starlight-room"},second.cookie),"buy usable room");
  const equipped=requireSuccess(await api("/api/equip",{inventoryId:roomPurchase.json.item_id},second.cookie),"equip owned world room");
  assert.equal(equipped.json.item,"starlight-room");
  const savedWorld=requireSuccess(await api("/api/bootstrap",undefined,second.cookie),"persist world customization");
  assert.equal(savedWorld.json.user.equipped_room,"starlight-room");
  const ineligible=savedWorld.json.inventory.find(x=>x.item_id==="starry-sticker");
  assert.ok(ineligible);
  const invalidEquip=await api("/api/equip",{inventoryId:ineligible.id},second.cookie);
  assert.equal(invalidEquip.status,400);
  console.log("PASS equipment ownership and type restrictions");
  const recovery=requireSuccess(await api("/api/recovery",{},cookie),"one-time recovery code");
  assert.match(recovery.json.code,/^[a-f0-9]{64}$/);
  const restored=requireSuccess(await api("/api/recover",{code:recovery.json.code}),"account recovery login");
  assert.ok(restored.cookie?.startsWith("pw_session="));
  const restoredProfile=requireSuccess(await api("/api/bootstrap",undefined,restored.cookie),"recovered account persisted");
  assert.equal(restoredProfile.json.user.display_name,name);
  assert.equal(restoredProfile.json.user.xp,25);
  const reuse=await api("/api/recover",{code:recovery.json.code});
  assert.equal(reuse.status,409);
  console.log("PASS one-time recovery code cannot be reused");
  for (const route of ["/privacy","/terms"]) {
    const legal=await fetch(ROOT+route);
    assert.equal(legal.status,200,route+" page");
    assert.match(await legal.text(),/Noetfield Systems Inc/);
    console.log("PASS "+route+" public page");
  }
  console.log("E2E SUCCESS — no cash transactions or real customer accounts created");
})().catch(err=>{console.error(err);process.exit(1);});
